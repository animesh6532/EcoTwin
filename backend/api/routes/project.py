@router.get("/raw-figure/{filename}")
def get_raw_figure(filename: str = Path(..., description="Image filename to fetch safely")):
    """
    Safe proxy route to serve figure images. Prevents path traversal and exposes correct media mime types.
    """
    if not re.match(r"^[0-9a-zA-Z_\-\.]+\.(png|jpg|jpeg|svg|webp)$", filename):
        raise HTTPException(status_code=400, detail="Invalid image filename format.")
        
    # Check main figures folder and spatial subfolder
    root_fig_path = project_service.figures_dir / filename
    spatial_fig_path = project_service.figures_dir / "spatial" / filename
    
    target_path = None
    if root_fig_path.exists():
        target_path = root_fig_path
    elif spatial_fig_path.exists():
        target_path = spatial_fig_path
        
    if not target_path:
        raise HTTPException(status_code=404, detail=f"Figure '{filename}' not found.")
        
    # Expose FileResponse safely
    return FileResponse(str(target_path))
