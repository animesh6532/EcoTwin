@router.get("/notebooks/{id}")
def get_notebook(id: str = Path(..., description="Target notebook filename e.g. '01_dataset_audit.ipynb'")):
    """
    Returns full details, cell blocks, and AST function listings for a notebook.
    """
    if not re.match(r"^[0-9a-zA-Z_\-\.]+\.ipynb$", id):
        raise HTTPException(status_code=400, detail="Invalid notebook filename format.")
        
    try:
        return project_service.get_notebook_details(id)
    except FileNotFoundError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

